import type { Map as PbMap } from "@gen/glyphoxa/management/v1/management_pb";

// What the Maps panel knows about a map's IMAGE, in one place: where its bytes
// are served, what the server will accept, and how to measure a picture before
// it is sent. Shared by the add dialog (CreateMap) and "Replace image"
// (ReplaceMapImage), so the two doors refuse the same files for the same reason.

/** The image byte route (a plain guarded mount — an <img> cannot speak Connect). */
export const mapImageURL = (map: PbMap) =>
  `/api/v1/maps/${map.id}/image?v=${map.updatedAt ? Number(map.updatedAt.seconds) : 0}`;

/** The blob seam's cap (ADR-0048, internal/blob.MaxSize). Stated in the UI BEFORE submit. */
export const MAP_IMAGE_MAX_MB = 32;
export const MAP_IMAGE_MAX_BYTES = MAP_IMAGE_MAX_MB * 1024 * 1024;

/**
 * The raster types the server stores (internal/blob.IsRasterImageType). SVG is
 * absent on purpose: the image mount serves the stored type same-origin.
 */
export const MAP_IMAGE_TYPES: readonly string[] = ["image/png", "image/jpeg", "image/webp", "image/gif"];
export const MAP_IMAGE_ACCEPT = MAP_IMAGE_TYPES.join(",");

export type ImageBytes = { bytes: Uint8Array; contentType: string };

/**
 * Why a picked file cannot become a map image, or null when it can. Checked in
 * the browser so the GM hears it at once, not after a 40 MB upload came back
 * refused.
 */
export function imageFileProblem(file: { type: string; size: number }): "type" | "size" | null {
  if (!MAP_IMAGE_TYPES.includes(file.type)) return "type";
  if (file.size > MAP_IMAGE_MAX_BYTES) return "size";
  return null;
}

/** "old_harbour-district.png" → "old harbour district": a first guess at the map's name. */
export function nameFromFile(filename: string): string {
  return filename
    .replace(/\.[^.]+$/, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * imageDimensions decodes just enough of a blob to read its pixel size.
 *
 * Takes a Blob rather than a File so it serves every door: an uploaded File and
 * the generated bytes (#541), which never were a file.
 *
 * The failure message is passed in (pre-translated by the caller) because this
 * helper runs outside React and must not bake in a display-language string.
 */
export function imageDimensions(file: Blob, unreadableMessage: string): Promise<{ width: number; height: number }> {
  return new Promise((resolve, reject) => {
    const url = URL.createObjectURL(file);
    const img = new Image();
    img.onload = () => {
      URL.revokeObjectURL(url);
      resolve({ width: img.naturalWidth, height: img.naturalHeight });
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      reject(new Error(unreadableMessage));
    };
    img.src = url;
  });
}

/** Reads a picked file into the bytes + dimensions both image RPCs take. */
export async function readImageFile(
  file: File,
  unreadableMessage: string,
): Promise<ImageBytes & { width: number; height: number }> {
  const bytes = new Uint8Array(await file.arrayBuffer());
  const dims = await imageDimensions(new Blob([bytes as BlobPart], { type: file.type }), unreadableMessage);
  return { bytes, contentType: file.type, ...dims };
}
